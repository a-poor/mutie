use super::*;
use crate::{
    cancellation::Cancellation,
    mutation::{Mutation, Operator, Scope, discover},
};
use anyhow::{Result, ensure};
use std::{fs, path::Path, time::Duration};

fn find(root: &Path, source: &str) -> Result<Vec<Mutation>> {
    fs::write(root.join("main.go"), source)?;
    Ok(
        discover(root, vec!["main.go".into()], &Scope::new(&[], &[])?)?
            .into_iter()
            .filter(|m| m.operator == Operator::StringReplace)
            .collect(),
    )
}

#[test]
fn string_sites_preserve_spans_and_value_contexts() -> Result<()> {
    let root = tempfile::tempdir()?;
    let source = r#"package p
import "fmt"
import ( alias "strings"; _ `unsafe` )
const C = "constant"
const (
    D = `grouped`
    E
)
type T struct { X string `json:"tag"`; Y string "tag2" }
type A [len("array type")]byte
var global = "global"
var collection = map[string]string{"key": "value"}
func f[T interface{ ~[len("type parameter")]byte }]() {
    // café
    const local = "local"
    _ = struct { X string `tag` }{X:"field value"}
    _ = map[string]string{"key": "map value"}["lookup"]
    _ = [len("array length")]string{"element"}
    switch "subject" { case "case", `raw case`: _ = "body"; default: _ = "default" }
    _ = func() string { return `closure` }
    _ = Named("converted")
    _ = ""
    _ = 'r'
}
"#
    .replace('\n', "\r\n");
    let found = find(root.path(), &source)?;
    assert_eq!(
        found.iter().map(Mutation::original).collect::<Vec<_>>(),
        [
            "\"global\"",
            "\"value\"",
            "\"field value\"",
            "\"map value\"",
            "\"lookup\"",
            "\"element\"",
            "\"subject\"",
            "\"body\"",
            "\"default\"",
            "`closure`",
            "\"converted\"",
            "\"\""
        ]
    );
    for m in found {
        assert!(valid_replacement(m.original(), &m.replacement));
        crate::identity::MutationIdentity::from(&m).validate()?;
        m.apply(root.path())?;
        assert_eq!(
            fs::read_to_string(root.path().join("main.go"))?,
            format!(
                "{}{}{}",
                &source[..m.range.start],
                m.replacement,
                &source[m.range.end..]
            )
        );
        assert!(m.apply(root.path()).is_err());
        fs::write(root.path().join("main.go"), &source)?;
    }
    for (name, text) in [
        ("sample_test.go", "package p\nvar x = \"test\""),
        (
            "generated.go",
            "// Code generated by test DO NOT EDIT.\npackage p\nvar x = \"generated\"",
        ),
    ] {
        fs::write(root.path().join(name), text)?;
        assert!(discover(root.path(), vec![name.into()], &Scope::new(&[], &[])?)?.is_empty());
    }
    Ok(())
}

#[test]
fn string_recipes_require_complete_tokens_and_valid_escapes() {
    for empty in ["\"\"", "``", "`\r`", "`\r\r`"] {
        assert_eq!(recipe(empty), Some("\"x\""), "{empty:?}");
    }
    for value in [
        "\"text\"",
        "\"\r\"",
        "`\n`",
        "`\r\n`",
        "`\\n`",
        "\"🦀\"",
        r#""\000""#,
        r#""\377""#,
        r#""\xFF""#,
        r#""\u0000""#,
        r#""\uFEFF""#,
        r#""\U0010FFFF""#,
    ] {
        assert_eq!(recipe(value), Some("\"\""), "{value:?}");
        assert!(!valid_replacement(value, "\"x\""));
    }
    for bad in [
        "",
        " \"a\"",
        "\"a\" ",
        "\"a\"+\"b\"",
        "\"a\";f()",
        "(\"a\")",
        "`a`+`b`",
        "\"a\"suffix",
        "r\"a\"",
        "'a'",
        "\"\n\"",
        "\"\\\n\"",
        "\"\0\"",
        "`\0`",
        "\"\u{feff}\"",
        "`\u{feff}`",
        r#""\0""#,
        r#""\00""#,
        r#""\400""#,
        r#""\777""#,
        r#""\8""#,
        r#""\x0""#,
        r#""\u123""#,
        r#""\ud800""#,
        r#""\U00110000""#,
        r#""\UFFFFFFFF""#,
        r#""\u{0}""#,
        r#""\q""#,
        r#""\'""#,
        "\"",
        "`",
    ] {
        assert_eq!(recipe(bad), None, "{bad:?}");
    }
    for wrong in ["``", "(\"\")", "\"value\"", "string(nil)"] {
        assert!(!valid_replacement("\"value\"", wrong));
    }
}

async fn command(root: &Path, args: &[&str]) -> Result<crate::process::CommandOutput> {
    let out = crate::process::run(
        "go",
        args,
        root,
        Duration::from_secs(30),
        std::num::NonZeroUsize::new(262144),
        &Cancellation::default(),
    )
    .await?;
    ensure!(
        !out.timed_out && out.capture_error.is_none(),
        "Go string probe exceeded bounds"
    );
    Ok(out)
}

#[tokio::test]
#[ignore = "requires Go and a writable cache; string bytes, types, escaping and raw CR semantics"]
async fn native_string_values_and_kinds() -> Result<()> {
    let cases: &[(&str, &[u8])] = &[
        ("\"\"", b""),
        ("``", b""),
        ("`\r`", b""),
        ("`\r\r`", b""),
        ("\"text\"", b"text"),
        ("`text`", b"text"),
        ("\"🦀\"", "🦀".as_bytes()),
        ("`🦀`", "🦀".as_bytes()),
        ("\"\r\"", b"\r"),
        ("\"\t\"", b"\t"),
        ("`a\nb`", b"a\nb"),
        ("`a\r\nb`", b"a\nb"),
        ("`a\rb`", b"ab"),
        ("`\\n`", b"\\n"),
        ("`\"`", b"\""),
        ("\"`\"", b"`"),
        (r#""\a\b\f\n\r\t\v\\\"""#, b"\x07\x08\x0c\n\r\t\x0b\\\""),
        (r#""\000""#, &[0]),
        (r#""\377""#, &[255]),
        (r#""\177""#, &[127]),
        (r#""\x00""#, &[0]),
        (r#""\xff""#, &[255]),
        (r#""\x80""#, &[128]),
        (r#""\u0000""#, &[0]),
        (r#""\u0080""#, &[194, 128]),
        (r#""\ufffd""#, &[239, 191, 189]),
        (r#""\uFEFF""#, &[239, 187, 191]),
        (r#""\U0010FFFF""#, &[244, 143, 191, 191]),
        (r#""\U0001F980""#, "🦀".as_bytes()),
        ("\"\u{2028}\u{2029}\"", "\u{2028}\u{2029}".as_bytes()),
        ("\"a\"[0:]", b"a"),
        ("\"\"[:]", b""),
    ];
    for newline in ["\n", "\r\n"] {
        let root = tempfile::tempdir()?;
        let mut source = "package main\nimport \"bytes\"\ntype Named string\n".to_owned();
        for (i, (expression, _)) in cases.iter().enumerate() {
            source.push_str(&format!(
                "func value{i}() {} {{ return {expression} }}\n",
                if i % 2 == 0 || i >= cases.len() - 2 {
                    "string"
                } else {
                    "Named"
                }
            ));
        }
        source = source.replace("\r\n", "\n").replace('\n', newline);
        let found = find(root.path(), &source)?;
        ensure!(
            found.len() == cases.len(),
            "expected {} sites, got {}",
            cases.len(),
            found.len()
        );
        for mutated in [false, true] {
            let mut code = source.clone();
            if mutated {
                for m in found.iter().rev() {
                    ensure!(
                        valid_replacement(m.original(), &m.replacement),
                        "invalid recipe"
                    );
                    code.replace_range(m.range.clone(), &m.replacement);
                }
            }
            code.push_str("\nfunc main() {\n");
            for (i, (_, original)) in cases.iter().enumerate() {
                let expected: &[u8] = if mutated {
                    if original.is_empty() { b"x" } else { b"" }
                } else {
                    original
                };
                let bytes = expected
                    .iter()
                    .map(u8::to_string)
                    .collect::<Vec<_>>()
                    .join(",");
                code.push_str(&format!(
                    "if !bytes.Equal([]byte(value{i}()), []byte{{{bytes}}}) {{ panic({i}) }}\n"
                ));
            }
            code.push_str("}\n");
            fs::write(root.path().join("main.go"), code)?;
            let out = command(root.path(), &["run", "main.go"]).await?;
            ensure!(
                out.status.success(),
                "mutated={mutated}: {}",
                out.stderr.text()?
            );
        }
    }
    Ok(())
}

#[tokio::test]
#[ignore = "requires Go; source restrictions and mutation-triggered constant compiler errors"]
async fn native_string_compiler_boundaries() -> Result<()> {
    let root = tempfile::tempdir()?;
    for expression in ["\"a\"[0]", "1 / len(\"a\")"] {
        let source = format!("package main\nfunc main() {{ _ = {expression} }}\n");
        let found = find(root.path(), &source)?;
        assert_eq!(found.len(), 1);
        let before = command(root.path(), &["build", "-o", "probe", "main.go"]).await?;
        ensure!(before.status.success(), "{}", before.stderr.text()?);
        found[0].apply(root.path())?;
        let after = command(root.path(), &["build", "-o", "probe", "main.go"]).await?;
        ensure!(
            !after.status.success(),
            "invalid constant operation compiled"
        );
        let stderr = after.stderr.text()?;
        ensure!(
            stderr.contains("out of bounds") || stderr.contains("division by zero"),
            "{stderr}"
        );
    }
    for expression in [
        "\"\0\"",
        "`\0`",
        "\"\u{feff}\"",
        "`\u{feff}`",
        r#""\ud800""#,
        r#""\400""#,
        r#""\'""#,
        "\"\\\n\"",
    ] {
        fs::write(
            root.path().join("main.go"),
            format!("package main\nfunc main() {{ _ = {expression} }}\n"),
        )?;
        let out = command(root.path(), &["build", "-o", "probe", "main.go"]).await?;
        ensure!(
            !out.status.success(),
            "{expression:?} was unexpectedly accepted"
        );
        assert_eq!(recipe(expression), None);
    }
    Ok(())
}
